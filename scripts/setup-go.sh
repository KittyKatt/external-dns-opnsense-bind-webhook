#!/usr/bin/env bash
#
# scripts/setup-go.sh — install a working Go toolchain for this repo.
#
# Why this exists:
#   - No root/apk in this sandbox, so "apk add go" is unavailable.
#   - $HOME/.cache is root-owned and unwritable, so the build/module caches
#     must be redirected to $HOME/tools.
#   - $HOME (and therefore $HOME/tools) is ephemeral; reinstalling on a fresh
#     container is fast (~1 min) and idempotent.
#
# Usage:
#   bash scripts/setup-go.sh        # install if needed, print a source line
#
# It is idempotent: if a valid Go is already installed it skips the download.
#
set -euo pipefail

GO_VERSION="${GO_VERSION:-1.22.12}"   # satisfies go.mod (1.22.2 / toolchain 1.22.3)
ARCH="amd64"
ROOT="${HOME}/tools"
GOROOT="$ROOT/go"
GO_TARBALL="$ROOT/go-${GO_VERSION}.linux-${ARCH}.tar.gz"
GO_ENV="$ROOT/go-env.sh"
GOPATH="$HOME/go"
GOBIN="$GOPATH/bin"
GOCACHE="$ROOT/gocache/go-build"
GOMODCACHE="$GOPATH/pkg/mod"

# sha256 for the pinned version above (published by go.dev/dl).
EXPECTED_SHA="4fa4f869b0f7fc6bb1eb2660e74657fbf04cdd290b5aef905585c86051b34d43"

if [ -x "$GOROOT/bin/go" ] && "$GOROOT/bin/go" version >/dev/null 2>&1; then
  echo "Go already installed at $GOROOT."
else
  echo "Installing Go ${GO_VERSION} -> ${GOROOT}"
  mkdir -p "$ROOT"
  URL="https://go.dev/dl/go${GO_VERSION}.linux-${ARCH}.tar.gz"
  echo "Downloading $URL"
  curl -fsSL -o "$GO_TARBALL" "$URL"

  ACTUAL_SHA="$(sha256sum "$GO_TARBALL" | awk '{print $1}')"
  if [ "$EXPECTED_SHA" != "$ACTUAL_SHA" ]; then
    echo "ERROR: sha256 mismatch (expected $EXPECTED_SHA, got $ACTUAL_SHA)" >&2
    exit 1
  fi
  echo "sha256 verified."

  rm -rf "$GOROOT"
  mkdir -p "$GOROOT"
  tar -C "$GOROOT" --strip-components=1 -xzf "$GO_TARBALL"
fi

# Caches: the default $HOME/.cache is root-owned here, so redirect them.
mkdir -p "$ROOT/gocache/go-build" "$HOME/go/pkg/mod"

# Emit a sourceable env file so the toolchain is one line away next time.
cat > "$GO_ENV" <<EOF
# Generated by scripts/setup-go.sh. Source this to use the Go toolchain.
export GOROOT="$GOROOT"
export GOPATH="$HOME/go"
export GOBIN="$HOME/go/bin"
export GOCACHE="$ROOT/gocache/go-build"
export GOMODCACHE="$HOME/go/pkg/mod"
export PATH="$GOROOT/bin:$GOBIN:$PATH"
EOF

echo
echo "Go $("$GOROOT/bin/go" version) installed."
echo "Next:  source $GO_ENV"
